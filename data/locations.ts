export function getLocation(slug: string): LocationData | undefined {
  return locations.find((l) => l.slug === slug);
}

export const zones = [
  "Downtown & Business",
  "Marina & JBR",
  "Jumeirah & Al Wasl",
  "Deira & Bur Dubai",
  "Al Barsha & Al Quoz",
  "Outer East",
  "Outer South & West",
  "Gated Communities",
] as const;

export type Zone = (typeof zones)[number];

export function getLocationsByZone(zone: Zone): LocationData[] {
  return locations.filter((l) => l.zone === zone);
}

export function getNearbyLocations(slug: string, count = 5): LocationData[] {
  const loc = getLocation(slug);
  if (!loc) return [];
  const sameZone = locations.filter((l) => l.zone === loc.zone && l.slug !== slug);
  const otherZone = locations.filter((l) => l.zone !== loc.zone);
  return [...sameZone, ...otherZone].slice(0, count);
}

export type LocationSlug = (typeof locations)[number]["slug"];
